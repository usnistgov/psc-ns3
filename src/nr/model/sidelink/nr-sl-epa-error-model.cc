double
NrSlEpaErrorModel::GetSci2ErrorRate(uint8_t mcs, uint8_t numerology, double snrDb) const
{
    NS_ASSERT_MSG(numerology <= 1, "Numerology 0-1 supported by this error model");
    const std::array<std::span<const double>, 29>* snrValuesByMcs15 = &SnrScs15Ntx1Rb10;
    const std::array<std::span<const double>, 29>* blerValuesByMcs15 = &BlerSci2Scs15Ntx1Rb10;
    const std::array<std::span<const double>, 29>* snrValuesByMcs30 = &SnrScs30Ntx1Rb10;
    const std::array<std::span<const double>, 29>* blerValuesByMcs30 = &BlerSci2Scs30Ntx1Rb10;
    NS_ASSERT_MSG(snrValuesByMcs15->size() > mcs,
                  "Error: mcs " << +mcs << " will overflow error table vector");
    NS_ASSERT_MSG(snrValuesByMcs30->size() > mcs,
                  "Error: mcs " << +mcs << " will overflow error table vector");
    if (numerology == 0)
    {
        return Interpolate(snrDb,
                           (*snrValuesByMcs15)[mcs],
                           (*blerValuesByMcs15)[mcs],
                           m_threshold,
                           m_extrapolationLimit);
    }
    else
    {
        return Interpolate(snrDb,
                           (*snrValuesByMcs30)[mcs],
                           (*blerValuesByMcs30)[mcs],
                           m_threshold,
                           m_extrapolationLimit);
    }
}

