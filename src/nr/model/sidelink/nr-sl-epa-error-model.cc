double
NrSlEpaErrorModel::GetTblerForNumTx(uint8_t mcs,
                                    uint8_t numerology,
                                    size_t numTx,
                                    double snrDb,
                                    uint32_t numRbs) const
{
    NS_LOG_FUNCTION(this << +mcs << +numerology << numTx << snrDb << numRbs);
    NS_ASSERT_MSG(numTx >= 1, "numTx must be at least 1");
    NS_ASSERT_MSG(numerology <= 1, "Numerology 0-1 supported by this error model");
    if (numTx > 5)
    {
        NS_LOG_WARN("No link simulation data for 6 or more transmissions; using 5 instead.");
        numTx = 5;
    }
    //
    // Two step process for the two sets of table data (corresponding to
    // two transport block sizes).  The first step is to obtain a TBLER
    // for the SNR value observed in the simulation, using both sets of
    // table data (one TBLER corresponding to the lowest TB size, and
    // one corresponding to the highest).  The second step is to interpolate
    // or extrapolate to the observed TB size.
    //
    const double (*erfcParamsOneSubch)[2] = (numerology == 0)
                                                ? ErfcParamsScs15Rb10ByNumTx[numTx - 1]
                                                : ErfcParamsScs30Rb10ByNumTx[numTx - 1];
    const double (*erfcParamsAllSubch)[2] = (numerology == 0)
                                                ? ErfcParamsScs15Rb50ByNumTx[numTx - 1]
                                                : ErfcParamsScs30Rb20ByNumTx[numTx - 1];
    double tblerOneSubch = GetTblerForMcs(snrDb, mcs, erfcParamsOneSubch);
    double tblerAllSubch = GetTblerForMcs(snrDb, mcs, erfcParamsAllSubch);
    NS_LOG_DEBUG("TBLER for one subchannel: " << tblerOneSubch
                                              << "; all subchannels: " << tblerAllSubch);
    // Interpolate/extrapolate TBLER based on transport block size
    return InterpolateTblerByRbs(tblerOneSubch, tblerAllSubch, numRbs, numerology);
}

double
NrSlEpaErrorModel::GetTbler(uint8_t mcs,
                            uint8_t numerology,
                            uint8_t rv,
                            double snrDb,
                            uint32_t tbSize,
                            uint32_t numRbs,
                            const NrErrorModel::NrErrorModelHistory& history) const
{
    NS_LOG_FUNCTION(this << mcs << numerology << rv << snrDb << tbSize << numRbs << history.size());
    std::set<uint8_t> rvHistory{rv};
    for (const auto& it : history)
    {
        rvHistory.insert(DynamicCast<NrSlErrorModelOutput>(it)->m_rv);
    }
    if (!rvHistory.contains(0) && !rvHistory.contains(3))
    {
        NS_LOG_DEBUG("Decoding not possible because neither RV 0 nor 3 have been received");
        return 1;
    }
    if (history.empty())
    {
        return GetTblerForNumTx(mcs, numerology, 1, snrDb, numRbs);
    }
    // Retransmission: combine the current snrDb with the SNR history
    // (see the error model documentation for this SNR combining rationale)
    auto averageSnr = GetAverageSnr(snrDb, history);
    NS_LOG_DEBUG("Average SNR of " << averageSnr << " for history size " << history.size());
    double jointTbler = GetTblerForNumTx(mcs, numerology, history.size() + 1, averageSnr, numRbs);
    // The reference curves are unconditional (joint) error probabilities,
    // but the previous attempts are known to have failed, so return the
    // conditional probability of failure given the failed history
    double priorJointTbler =
        GetTblerForNumTx(mcs, numerology, history.size(), GetAverageSnr(history), numRbs);
    return ComputeConditionalTbler(jointTbler, priorJointTbler);
}

