// The link simulation data is from a NIST LLS configuration of 10 RBs per subchannel in and
// a 10 MHz band n14. For numerology 0, 10 RBs (one subchannel) and 50 RBs (five subchannels)
// were simulated; for numerology 1, 10 RBs and 20 RBs (two subchannels) were simulated.
static constexpr uint32_t RB_ONE_SUBCH = 10;
static constexpr uint32_t RB_ALL_SUBCH_SCS15 = 50;
static constexpr uint32_t RB_ALL_SUBCH_SCS30 = 20;

// Number of MCS values (0-28) in each data table
static constexpr uint32_t NUM_MCS = 29;

double
NrSlEpaErrorModel::InterpolateTblerByRbs(double tblerOneSubch,
                                         double tblerAllSubch,
                                         uint32_t numRbs,
                                         uint8_t numerology) const
{
    NS_LOG_FUNCTION(this << tblerOneSubch << tblerAllSubch << numRbs << numerology);
    uint32_t rbsAllSubch = (numerology == 0) ? RB_ALL_SUBCH_SCS15 : RB_ALL_SUBCH_SCS30;

    NS_LOG_DEBUG("numRbs " << numRbs << " rbsOneSubch " << RB_ONE_SUBCH << " rbsAllSubch "
                           << rbsAllSubch);

    // Handle edge case: if numRbs is at or below minimum, return tblerOneSubch
    if (numRbs <= RB_ONE_SUBCH)
    {
        NS_LOG_DEBUG("Returning TBLER for one subchannel: " << tblerOneSubch);
        return tblerOneSubch;
    }

    // If both TBLERs are below the reliability threshold, return zero
    if (tblerOneSubch < m_extrapolationLimit && tblerAllSubch < m_extrapolationLimit)
    {
        NS_LOG_DEBUG("Returning TBLER of zero (both values below reliability threshold)");
        return 0.0;
    }

    // Calculate the weight for interpolation/extrapolation, performed in log domain
    // w = (log(RBs) - log(RBs_1)) / (log(RBs_max) - log(RBs_1))
    double logRb = std::log(static_cast<double>(numRbs));
    double logRb1 = std::log(static_cast<double>(RB_ONE_SUBCH));
    double logRbMax = std::log(static_cast<double>(rbsAllSubch));
    double w = (logRb - logRb1) / (logRbMax - logRb1);

    // Special handling for extrapolation (w > 1) when single-subchannel TBLER is unreliable
    // but multi-subchannel TBLER is reliable. Use power-law extrapolation from the known
    // data point to avoid a problematic log-linear extrapolation with an artificial floor.
    // Alpha is computed dynamically to ensure continuity with log-linear extrapolation
    // at the boundary where tbler1 = m_extrapolationLimit.
    if (w > 1.0 && tblerOneSubch < m_extrapolationLimit && tblerAllSubch >= m_extrapolationLimit)
    {
        // Compute alpha to match log-linear result at boundary (tbler1 = m_extrapolationLimit)
        // alpha = (log(tblerMax) - log(m_extrapolationLimit)) / (log(RBs_max) - log(RBs_1))
        double alpha =
            (std::log(tblerAllSubch) - std::log(m_extrapolationLimit)) / (logRbMax - logRb1);
        double rbRatio = static_cast<double>(numRbs) / static_cast<double>(rbsAllSubch);
        double result = std::min(1.0, tblerAllSubch * std::pow(rbRatio, alpha));
        // If result is below reliability threshold, treat as zero
        if (result < m_extrapolationLimit)
        {
            NS_LOG_DEBUG("Extrapolation result " << result
                                                 << " below reliability threshold, returning 0");
            return 0.0;
        }
        NS_LOG_DEBUG("Extrapolation with unreliable tbler1: using power-law (alpha="
                     << alpha << "), RB ratio=" << rbRatio << ", result=" << result);
        return result;
    }

    // Special handling for interpolation (w <= 1) when multi-subchannel TBLER is unreliable
    // but single-subchannel TBLER is reliable. The larger RB allocation has effectively zero
    // errors at this SNR, so return zero to avoid an artificial floor from floored tblerMax.
    if (w <= 1.0 && tblerAllSubch < m_extrapolationLimit && tblerOneSubch >= m_extrapolationLimit)
    {
        NS_LOG_DEBUG("Interpolation with unreliable tblerAllSubch: returning 0");
        return 0.0;
    }

    // Floor unreliable values to the threshold for standard interpolation/extrapolation
    double tbler1 = std::max(tblerOneSubch, m_extrapolationLimit);
    double tblerMax = std::max(tblerAllSubch, m_extrapolationLimit);

    NS_LOG_DEBUG("TBLER 1 subchannel " << tbler1 << " max subchannels " << tblerMax);

    // Calculate log(TBLER) = (1 - w) * log(TBLER_1) + w * log(TBLER_max)
    double logTbler1 = std::log(tbler1);
    double logTblerMax = std::log(tblerMax);
    double logTblerN = (1.0 - w) * logTbler1 + w * logTblerMax;

    double result = std::min(1.0, std::exp(logTblerN));
    // If result is below reliability threshold, treat as zero
    if (result < m_extrapolationLimit)
    {
        NS_LOG_DEBUG("Interpolated result " << result
                                            << " below reliability threshold, returning 0");
        return 0.0;
    }
    NS_LOG_DEBUG("Returning interpolated/extrapolated TBLER: " << result);
    return result;
}

double
NrSlEpaErrorModel::InterpolateWithErfc(double snrDb, double mu, double sigma) const
{
    NS_LOG_FUNCTION(this << snrDb << mu << sigma);

    // Use the erfc model for the full TBLER range. The erfc parameters
    // (mu, sigma) were fit to the reference data in [0.01, 1.0]. Using
    // erfc everywhere avoids the discontinuity that occurs when switching
    // between table interpolation and erfc at a crossover point.
    double tbler = std::min(1.0, 0.5 * std::erfc((snrDb - mu) / (sigma * std::sqrt(2.0))));
    if (tbler < m_extrapolationLimit)
    {
        NS_LOG_DEBUG("erfc result below extrapolation limit, returning 0");
        return 0.0;
    }
    NS_LOG_DEBUG("erfc result: " << tbler << " at SNR " << snrDb << " (mu=" << mu
                                 << ", sigma=" << sigma << ")");
    return tbler;
}

double
NrSlEpaErrorModel::GetTblerForMcs(double snrDb, uint8_t mcs, const double (*erfcParams)[2]) const
{
    NS_ASSERT_MSG(mcs < NUM_MCS, "Error: mcs " << +mcs << " will overflow error table vector");
    double mu = erfcParams[mcs][0];
    double sigma = erfcParams[mcs][1];
    return InterpolateWithErfc(snrDb, mu, sigma);
}

