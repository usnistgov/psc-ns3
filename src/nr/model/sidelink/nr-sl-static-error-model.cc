double
NrSlStaticErrorModel::GetSci2ErrorRate(uint8_t mcs, uint8_t numerology, double snrDb) const
{
    // For the static channel, numerology is not considered
    NS_ASSERT_MSG(numerology <= 2, "Numerology 0-2 supported by sidelink");
    const std::array<std::span<const double>, 29>* snrValuesByMcs = &SnrScs15Ntx1;
    const std::array<std::span<const double>, 29>* blerValuesByMcs = &BlerSci2Scs15Ntx1;
    NS_ASSERT_MSG(snrValuesByMcs->size() > mcs,
                  "Error: mcs " << +mcs << " will overflow error table vector");
    return Interpolate(snrDb,
                       (*snrValuesByMcs)[mcs],
                       (*blerValuesByMcs)[mcs],
                       m_threshold,
                       m_extrapolationLimit);
}

double
NrSlStaticErrorModel::GetTbler(uint8_t mcs,
                               uint8_t numerology,
                               uint8_t rv,
                               double snrDb,
                               uint32_t tbSize,
                               uint32_t numRbs,
                               const NrErrorModel::NrErrorModelHistory& history) const
{
    NS_LOG_FUNCTION(this << mcs << numerology << rv << snrDb << tbSize << numRbs << history.size());
    // For the static channel, numerology is not considered
    NS_ASSERT_MSG(numerology <= 2, "Numerology 0-2 defined for sidelink");
    std::set<uint8_t> rvHistory{rv};
    for (const auto& it : history)
    {
        rvHistory.insert(DynamicCast<NrSlErrorModelOutput>(it)->m_rv);
    }
    if (!rvHistory.contains(0) && !rvHistory.contains(3))
    {
        NS_LOG_DEBUG("Decoding not possible because neither RV 0 nor 3 have been received");
        return 1;
    }
    if (history.empty())
    {
        return GetTblerForNumTx(mcs, 1, snrDb);
    }
    // Retransmission: combine the current snrDb with the SNR history
    // (see the error model documentation for this SNR combining rationale)
    auto averageSnr = GetAverageSnr(snrDb, history);
    NS_LOG_DEBUG("Average SNR of " << averageSnr << " for history size " << history.size());
    double jointTbler = GetTblerForNumTx(mcs, history.size() + 1, averageSnr);
    // The reference curves are unconditional (joint) error probabilities,
    // but the previous attempts are known to have failed, so return the
    // conditional probability of failure given the failed history
    double priorJointTbler = GetTblerForNumTx(mcs, history.size(), GetAverageSnr(history));
    return ComputeConditionalTbler(jointTbler, priorJointTbler);
}

// Reference curve tables indexed by [number of transmissions - 1]
static constexpr std::array<const std::array<std::span<const double>, 29>*, 5> SnrScs15ByNumTx =
    {&SnrScs15Ntx1, &SnrScs15Ntx2, &SnrScs15Ntx3, &SnrScs15Ntx4, &SnrScs15Ntx5};
static constexpr std::array<const std::array<std::span<const double>, 29>*, 5> BlerScs15ByNumTx =
    {&BlerScs15Ntx1, &BlerScs15Ntx2, &BlerScs15Ntx3, &BlerScs15Ntx4, &BlerScs15Ntx5};

double
NrSlStaticErrorModel::GetTblerForNumTx(uint8_t mcs, size_t numTx, double snrDb) const
{
    NS_LOG_FUNCTION(this << +mcs << numTx << snrDb);
    NS_ASSERT_MSG(numTx >= 1, "numTx must be at least 1");
    if (numTx > 5)
    {
        NS_LOG_WARN("No link simulation data for 6 or more transmissions; using 5 instead.");
        numTx = 5;
    }
    // Static channel BLER performance is insensitive to numerology
    // so use numerology 0 results for all
    const auto* snrValuesByMcs = SnrScs15ByNumTx[numTx - 1];
    const auto* blerValuesByMcs = BlerScs15ByNumTx[numTx - 1];
    NS_ASSERT_MSG(snrValuesByMcs->size() > mcs,
                  "Error: mcs " << +mcs << " will overflow error table vector");
    return Interpolate(snrDb,
                       (*snrValuesByMcs)[mcs],
                       (*blerValuesByMcs)[mcs],
                       m_threshold,
                       m_extrapolationLimit);
}

